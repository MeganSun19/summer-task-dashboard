import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = fileURLToPath(new URL("..", import.meta.url));
const sourcePath = join(projectRoot, "curriculum", "learning-module-catalog.json");
const outputPath = join(projectRoot, "curriculum", "learning-module-catalog.js");
const checkOnly = process.argv.slice(2).includes("--check");
const unsupportedArguments = process.argv.slice(2).filter((argument) => argument !== "--check");

if (unsupportedArguments.length) {
  console.error(`不支持的参数：${unsupportedArguments.join(", ")}`);
  process.exit(2);
}

function fail(message) {
  throw new Error(`模块目录无效：${message}`);
}

function requireNonEmptyString(value, path) {
  if (typeof value !== "string" || !value.trim()) fail(`${path} 必须是非空字符串`);
}

function requireStringArray(value, path) {
  if (!Array.isArray(value) || value.some((item) => typeof item !== "string" || !item.trim())) {
    fail(`${path} 必须是字符串数组`);
  }
}

function validateCatalog(catalog) {
  if (!catalog || typeof catalog !== "object" || Array.isArray(catalog)) fail("根节点必须是对象");
  if (catalog.schemaVersion !== 1) fail("schemaVersion 必须为 1");
  if (!Array.isArray(catalog.modules) || !catalog.modules.length) fail("modules 必须是非空数组");

  const ids = new Set();
  catalog.modules.forEach((module, index) => {
    const path = `modules[${index}]`;
    if (!module || typeof module !== "object" || Array.isArray(module)) fail(`${path} 必须是对象`);
    requireNonEmptyString(module.id, `${path}.id`);
    if (!/^[A-Za-z][A-Za-z0-9]*$/.test(module.id)) fail(`${path}.id 只能使用英文和数字并以英文字母开头`);
    if (ids.has(module.id)) fail(`${path}.id 与其他模块重复：${module.id}`);
    ids.add(module.id);

    requireNonEmptyString(module.title, `${path}.title`);
    requireStringArray(module.tags, `${path}.tags`);
    requireNonEmptyString(module.instruction, `${path}.instruction`);
    if ((typeof module.detail !== "string" || !module.detail.trim()) && !Array.isArray(module.details)) {
      fail(`${path} 必须提供 detail 或 details`);
    }
    if (module.detail !== undefined) requireNonEmptyString(module.detail, `${path}.detail`);
    if (module.contentKey !== undefined) requireNonEmptyString(module.contentKey, `${path}.contentKey`);
    if (module.details !== undefined) {
      requireStringArray(module.details, `${path}.details`);
      if (!module.details.length) fail(`${path}.details 不能为空`);
      if (!new Set(["day", "week"]).has(module.cycle)) fail(`${path}.cycle 必须是 day 或 week`);
    }
    if (module.scheduledOnly !== undefined && typeof module.scheduledOnly !== "boolean") {
      fail(`${path}.scheduledOnly 必须是布尔值`);
    }

    const presentation = module.presentation;
    if (!presentation || typeof presentation !== "object" || Array.isArray(presentation)) {
      fail(`${path}.presentation 必须是对象`);
    }
    requireNonEmptyString(presentation.icon, `${path}.presentation.icon`);
    for (const colorKey of ["color", "soft"]) {
      if (typeof presentation[colorKey] !== "string" || !/^#[0-9a-fA-F]{6}$/.test(presentation[colorKey])) {
        fail(`${path}.presentation.${colorKey} 必须是六位十六进制颜色`);
      }
    }
    if (!Number.isInteger(presentation.minutes) || presentation.minutes <= 0) {
      fail(`${path}.presentation.minutes 必须是正整数`);
    }

    if (module.activity !== undefined) {
      if (!module.activity || typeof module.activity !== "object" || Array.isArray(module.activity)) {
        fail(`${path}.activity 必须是对象`);
      }
      for (const key of ["type", "renderer", "source"]) {
        requireNonEmptyString(module.activity[key], `${path}.activity.${key}`);
      }
    }
  });
}

function render(modules) {
  const json = JSON.stringify(modules, null, 2).replaceAll("\n", "\n  ");
  return `(function (root) {\n  // Generated by scripts/generate-learning-module-catalog.mjs. Do not edit directly.\n  root.LEARNING_MODULE_CATALOG = Object.freeze(${json});\n})(typeof window === "undefined" ? globalThis : window);\n`;
}

const catalog = JSON.parse(readFileSync(sourcePath, "utf8"));
validateCatalog(catalog);
const generated = render(catalog.modules);

if (checkOnly) {
  const current = readFileSync(outputPath, "utf8");
  if (current !== generated) {
    console.error("模块目录生成结果已过期。请运行：node scripts/generate-learning-module-catalog.mjs");
    process.exit(1);
  }
  console.log(`OK: 模块目录已校验（${catalog.modules.length} 个模块）`);
} else {
  writeFileSync(outputPath, generated);
  console.log(`已生成 curriculum/learning-module-catalog.js（${catalog.modules.length} 个模块）`);
}
